export const DIR_NAME = { cw: '外回り', ccw: '内回り' };

// 1周の所要分と、各駅の路線図上の角度（所要時間に比例）
for (const L of Object.values(LINES)) {
  L.total = L.st.reduce((a, s) => a + s[2], 0);
  let c = 0;
  L.ang = L.st.map(s => { const a = L.start + c / L.total * Math.PI * 2; c += s[2]; return a; });
}

const step = (L, i, dir) => dir === 'cw' ? (i + 1) % L.st.length : (i - 1 + L.st.length) % L.st.length;
export const segMin = (L, i, j, dir) => dir === 'cw' ? L.st[i][2] : L.st[j][2];

// from から to までに通る駅の番号。from === to なら一周
export function makePath(L, from, to, dir) {
  const p = [from];
  let i = step(L, from, dir);
  while (i !== to) { p.push(i); i = step(L, i, dir); }
  p.push(to);
  return p;
}
export function pathMin(L, p, dir) {
  let m = 0;
  for (let k = 0; k < p.length - 1; k++) m += segMin(L, p[k], p[k + 1], dir);
  return m;
}
// 経路の終点の角度（一周しても連続になるよう巻き戻さない）
export const endAngle = (L, from, min, dir) => L.ang[from] + (dir === 'cw' ? 1 : -1) * min / L.total * Math.PI * 2;
